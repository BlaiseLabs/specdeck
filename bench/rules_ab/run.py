"""Do agents keep a project's rules better with specdeck's AGENTS.md?

A small shop package has six rules of the kind people write into CLAUDE.md ("never use float for
money", "never call datetime.now() directly"). Six feature tasks each tempt one or more of them;
every task's acceptance test passes for a rule-breaking solution too. One agent (terra, with a
read-only shell, file edits and a test runner) does each task under four arms:

  N   no AGENTS.md, no rule tests                      how often the rules are broken unprompted
  P   AGENTS.md with the rules as plain bullets         the usual hand-written file
  PT  P, plus a test per rule in the suite              the hand-rolled "rules backed by scripted checks"
  S   specdeck: the rules as requirements, the same tests linked to them, AGENTS.md generated by
      `specdeck agents` (statement, reason, verifying test, status), and the specdeck plugin on

AGENTS.md is given to the agent as instructions, as coding agents do. Graded on the final tree:
the acceptance test passes, the original tests pass, and which rules are broken (pristine checks).

    python3 run.py --cap 1000000 --reps 2
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from dotenv import load_dotenv
from openai import OpenAI

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "navigate"))
import agent as nav  # noqa: E402  (its read-only shell)
from rules import RULES  # noqa: E402
from tasks import PRESSURE, TASKS  # noqa: E402

load_dotenv("/workspaces/python/.env")
MODEL = os.environ.get("RULES_MODEL", "gpt-5.6-terra")
LOG = HERE / os.environ.get("RULES_LOG", "results.jsonl")
TRIAL_CAP = int(os.environ.get("RULES_TRIAL_CAP", "80000"))   # total tokens, checked before each call
MAX_CALLS = 30
ARMS = ("N", "P", "PT", "S")


# --------------------------------------------------------------------------- materials per arm
def rules_tests(linked: bool) -> str:
    t = (HERE / "rules_template.py").read_text()
    t = t.replace("{IMPORT}", "\nfrom specdeck import scenario\n" if linked else "")
    for key, rid, *_ in RULES:
        dec = f'@scenario("rule-{key.replace("_", "-")}", covers=["{rid}"])\n' if linked else ""
        t = t.replace("{DEC_" + key + "}\n", dec)
    return t


def plain_agents() -> str:
    lines = ["# AGENTS.md", "", "Rules for this repository:", ""]
    lines += [f"- {plain}" for _, _, plain, _, _ in RULES]
    return "\n".join(lines + ["", "Run `pytest` before you finish.", ""])


def requirements_yaml() -> str:
    out = ["requirements:"]
    for _, rid, _, statement, why in RULES:
        out += [f"  - id: {rid}", f"    statement: {json.dumps(statement, ensure_ascii=False)}",
                f"    rationale: {json.dumps(why, ensure_ascii=False)}", "    type: design-constraint",
                "    verification: test"]
    return "\n".join(out) + "\n"


def specdeck_agents() -> str:
    """AGENTS.md as `specdeck agents` writes it after a real run of the fixture with its rules."""
    cached = HERE / "materials" / "AGENTS.specdeck.md"
    if cached.exists():
        return cached.read_text()
    d = Path(tempfile.mkdtemp(prefix="rules-gen-")) / "shop"
    shutil.copytree(HERE / "fixture", d)
    (d / "tests" / "test_rules.py").write_text(rules_tests(True))
    (d / "requirements.yaml").write_text(requirements_yaml())
    subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"], cwd=d, capture_output=True)
    subprocess.run([sys.executable, "-m", "specdeck", "agents"], cwd=d, check=True, capture_output=True)
    cached.parent.mkdir(exist_ok=True)
    cached.write_text((d / "AGENTS.md").read_text())
    return cached.read_text()


def build(arm: str, task: str) -> Path:
    d = Path(tempfile.mkdtemp(prefix=f"rules-{arm}-{task}-")) / "shop"
    shutil.copytree(HERE / "fixture", d)
    (d / "tests" / "test_task.py").write_text(TASKS[task][1])
    if arm in ("P", "PT"):
        (d / "AGENTS.md").write_text(plain_agents())
    if arm == "PT":
        (d / "tests" / "test_rules.py").write_text(rules_tests(False))
    if arm == "S":
        (d / "tests" / "test_rules.py").write_text(rules_tests(True))
        (d / "requirements.yaml").write_text(requirements_yaml())
        (d / "AGENTS.md").write_text(specdeck_agents())
    return d


# --------------------------------------------------------------------------- the agent's tools
TOOLS = [
    {"type": "function", "name": "bash", "description": "Run a read-only shell command in the repository root "
     "(ls, cat, grep, sed -n, nl, find, head, tail, wc), combined with pipes.",
     "parameters": {"type": "object", "properties": {"command": {"type": "string"}}, "required": ["command"]}},
    {"type": "function", "name": "write_file", "description": "Create or overwrite a file with the given content. "
     "Allowed: files under src/, and pyproject.toml. Tests and AGENTS.md cannot be changed.",
     "parameters": {"type": "object", "properties": {"path": {"type": "string"}, "content": {"type": "string"}},
                    "required": ["path", "content"]}},
    {"type": "function", "name": "replace_lines", "description": "Replace lines start..end (1-based, inclusive) "
     "of a file with new text. Same files as write_file.",
     "parameters": {"type": "object", "properties": {"path": {"type": "string"}, "start": {"type": "integer"},
                                                     "end": {"type": "integer"}, "new": {"type": "string"}},
                    "required": ["path", "start", "end", "new"]}},
    {"type": "function", "name": "run_tests", "description": "Run the test suite (pytest) and show the result.",
     "parameters": {"type": "object", "properties": {}}},
]


def _editable(tree: Path, rel: str):
    rel = rel.strip().lstrip("./") if not rel.startswith("../") else rel
    if ".." in Path(rel).parts or rel.startswith("/"):
        return None
    if rel == "pyproject.toml" or (rel.startswith("src/") and rel.endswith((".py", ".json", ".toml", ".txt", ".csv"))):
        return tree / rel
    return None


def write_file(tree: Path, rel: str, content: str) -> str:
    p = _editable(tree, rel)
    if p is None:
        return "rejected: only files under src/ and pyproject.toml can be written"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(content)
    return "written"


def replace_lines(tree: Path, rel: str, s: int, e: int, new: str) -> str:
    p = _editable(tree, rel)
    if p is None or not p.is_file():
        return "rejected: not an editable file"
    lines = p.read_text().splitlines()
    if not 1 <= s <= e <= len(lines):
        return f"rejected: bad range (file has {len(lines)} lines)"
    lines[s - 1:e] = new.split("\n") if new else []
    p.write_text("\n".join(lines) + "\n")
    return "applied"


def run_tests(tree: Path, arm: str, files=()) -> tuple:
    plugin = [] if arm == "S" else ["-p", "no:specdeck"]
    env = {**os.environ, "PYTHONPATH": str(tree / "src")}
    p = subprocess.run([sys.executable, "-m", "pytest", "-q", "--tb=short", "-p", "no:cacheprovider",
                        "-p", "no:randomly", "-p", "no:asyncio", *plugin, *files], cwd=tree, env=env, capture_output=True,
                       text=True, timeout=300)
    return p.returncode, (p.stdout + p.stderr)[-6000:]


SYSTEM = ("You are a coding agent working in a Python repository. Use the tools to complete the task. "
          "When you are done, reply with a one-line summary.")
TASK = "Task:\n{task}\n\ntests/test_task.py checks the feature."
PRESSURED = os.environ.get("RULES_PRESSURE") == "1"   # append the teammate's nudge against a rule


def agent(client, tree: Path, arm: str, task: str, rows: list) -> dict:
    instructions = SYSTEM
    if (tree / "AGENTS.md").exists():
        instructions += "\n\nThe repository's AGENTS.md:\n\n" + (tree / "AGENTS.md").read_text()
    text = TASKS[task][0] + (" " + PRESSURE[task] if PRESSURED else "")
    pending = [{"role": "user", "content": TASK.format(task=text)}]
    prev, calls, log, test_runs = None, 0, [], []
    final = ""
    while calls < MAX_CALLS and sum(r["total"] for r in rows) < TRIAL_CAP:
        kw = {"previous_response_id": prev} if prev else {}
        r = client.responses.create(model=MODEL, instructions=instructions, input=pending, tools=TOOLS, **kw)
        u = r.usage
        rows.append({"input": u.input_tokens, "output": u.output_tokens,
                     "cached": getattr(u.input_tokens_details, "cached_tokens", 0) or 0, "total": u.total_tokens})
        prev = r.id
        fcalls = [o for o in r.output if getattr(o, "type", "") == "function_call"]
        if not fcalls:
            final = (r.output_text or "")[:300]
            break
        pending = []
        for fc in fcalls:
            calls += 1
            try:
                a = json.loads(fc.arguments or "{}")
            except json.JSONDecodeError:
                a = {}
            if fc.name == "bash":
                res = nav.run_cmd(str(a.get("command", "")), tree)
            elif fc.name == "write_file":
                res = write_file(tree, str(a.get("path", "")), str(a.get("content", "")))
            elif fc.name == "replace_lines":
                try:
                    res = replace_lines(tree, str(a.get("path", "")), int(a["start"]), int(a["end"]), str(a.get("new", "")))
                except (KeyError, TypeError, ValueError):
                    res = "rejected: need path, start, end, new"
            else:
                rc, res = run_tests(tree, arm)
                failed = sorted(set(re.findall(r"FAILED tests/(\w+\.py)::(\w+)", res)))
                test_runs.append({"rc": rc, "failed": [f"{f}::{n}" for f, n in failed],
                                  "rule_failures": sum(1 for f, _ in failed if f == "test_rules.py")})
            log.append({"tool": fc.name, "arg": (a.get("command") or a.get("path") or "")[:120], "result": str(res)[:200]})
            pending.append({"type": "function_call_output", "call_id": fc.call_id, "output": str(res)})
    return {"tool_calls": calls, "log": log, "test_runs": test_runs, "final": final}


# --------------------------------------------------------------------------- grading
def _checks():
    spec = importlib.util.spec_from_file_location("pristine_rules", HERE / "_pristine_rules.py")
    (HERE / "_pristine_rules.py").write_text(rules_tests(False))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return {key: getattr(mod, f"check_{key}") for key, *_ in RULES}


CHECKS = None


def grade(tree: Path, task: str) -> dict:
    global CHECKS
    CHECKS = CHECKS or _checks()
    pristine = tree.parent / "pristine"
    pristine.mkdir(exist_ok=True)
    (pristine / "test_task.py").write_text(TASKS[task][1])
    shutil.copy(HERE / "fixture" / "tests" / "test_orders.py", pristine / "test_orders.py")
    shutil.copy(HERE / "fixture" / "tests" / "conftest.py", pristine / "conftest.py")
    env = {**os.environ, "PYTHONPATH": str(tree / "src")}
    res = {}
    for name in ("test_task.py", "test_orders.py"):
        p = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "-p", "no:specdeck",
                            "--rootdir", str(pristine), str(pristine / name)], cwd=tree, env=env,
                           capture_output=True, text=True, timeout=300)
        res[name] = p.returncode == 0
    violations = {key: fn(tree / "src" / "shop") for key, fn in CHECKS.items()}
    return {"accept": res["test_task.py"], "base": res["test_orders.py"],
            "violations": {k: v for k, v in violations.items() if v},
            "broken": sorted(k for k, v in violations.items() if v)}


def trial(client, arm: str, task: str, rep: int) -> dict:
    tree = build(arm, task)
    rows, t0 = [], time.time()
    try:
        detail, err = agent(client, tree, arm, task, rows), None
    except Exception as exc:  # noqa: BLE001
        detail, err = {}, repr(exc)[:300]
    g = grade(tree, task)
    return {"arm": arm, "task": task, "rep": rep, "model": MODEL, "pressure": PRESSURED, **g, "error": err,
            "seconds": round(time.time() - t0), "tokens": sum(r["total"] for r in rows),
            "uncached": sum(r["total"] - r["cached"] for r in rows), "capped": sum(r["total"] for r in rows) >= TRIAL_CAP,
            "ledger": rows, "detail": detail, "tree": str(tree)}


def spent() -> int:
    return sum(json.loads(l)["tokens"] for l in LOG.read_text().splitlines() if l.strip()) if LOG.exists() else 0


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cap", type=int, required=True, help="total tokens for the whole run, cached included")
    ap.add_argument("--reps", type=int, default=1)
    ap.add_argument("--arms", default=",".join(ARMS))
    ap.add_argument("--tasks", default=",".join(TASKS))
    ap.add_argument("--workers", type=int, default=6)
    a = ap.parse_args()
    specdeck_agents()
    done = set()
    if LOG.exists():
        for l in LOG.read_text().splitlines():
            r = json.loads(l)
            done.add((r["arm"], r["task"], r["rep"]))
    # rep by rep, every arm on a task together, so a cap that stops the run leaves a balanced set
    jobs = [(arm, task, rep) for rep in range(a.reps) for task in a.tasks.split(",") for arm in a.arms.split(",")
            if (arm, task, rep) not in done]
    print(f"{len(jobs)} trials, spent {spent():,} of {a.cap:,}", flush=True)
    client = OpenAI()

    def go(job):
        if spent() > a.cap - TRIAL_CAP:
            return
        row = trial(client, *job)
        with LOG.open("a") as fh:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")
        runs = row["detail"].get("test_runs", []) if row["detail"] else []
        print(f"{row['arm']:2} {row['task']:8} r{row['rep']} accept={row['accept']} base={row['base']} "
              f"broken={','.join(row['broken']) or '-'} tests_run={len(runs)} tok={row['tokens']:,} "
              f"{row['seconds']}s err={row['error'] or ''} | spent {spent():,}", flush=True)
    with ThreadPoolExecutor(a.workers) as ex:
        list(ex.map(go, jobs))


if __name__ == "__main__":
    main()
