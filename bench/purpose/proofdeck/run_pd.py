"""Business-purpose replication on proofdeck: same agent (navigate/agent.py), same limits as
v2/v3 (past 40k tokens the next call must answer; abort past 60k), same cap guard.

  python run_pd.py --round 0          # one session per core arm, in that round's order
  python run_pd.py --arms specdeck --seed 0
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
from pathlib import Path

from dotenv import load_dotenv
from openai import OpenAI

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent.parent / "navigate"))
import agent  # noqa: E402
sys.path.insert(0, str(HERE))
import build_pd  # noqa: E402
from questions_pd import QUESTIONS  # noqa: E402

LOG = HERE / "trials_proofdeck.jsonl"
MODEL = "gpt-5.6-terra"
CAP = 520_000
SOFT_CAP = 40_000
SESSION_CAP = 60_000
HEADROOM = 85_000
CORE = ["plain", "separate_doc", "specdeck_prompt"]


class SessionOver(Exception):
    pass


class Metered:
    """The same metering as purpose/run.py: count every call's usage; past SOFT_CAP the next
    call gets no tools and is told to answer; past SESSION_CAP abort; never cross the cap."""

    forced = False

    def __init__(self, client, preface: str = "", left: int = 10**9):
        self._client, self.tokens, self.calls = client, 0, []
        self.left, self.next_est, self.preface = left, 0, preface
        self.responses = self

    def create(self, **kw):
        if self.tokens > SOFT_CAP and "tools" in kw:
            kw.pop("tools")
            kw["input"] = list(kw["input"]) + [{"role": "user", "content":
                                                "Tool budget used up. Answer now with the JSON object."}]
            self.forced = True
        elif self.tokens > SESSION_CAP:
            raise SessionOver(self.tokens)
        if self.tokens + self.next_est > self.left:
            raise SessionOver(self.tokens)
        if self.preface and "previous_response_id" not in kw:
            kw["input"] = [dict(m) for m in kw["input"]]
            user = next(m for m in kw["input"] if m.get("role") == "user")
            user["content"] = self.preface + "\n\n" + user["content"]
        r = self._client.responses.create(**kw)
        self.tokens += r.usage.total_tokens
        self.next_est = r.usage.total_tokens + 10_000
        self.calls.append(r.usage.total_tokens)
        self.last_text = r.output_text or ""
        return r


def rows() -> list:
    return [json.loads(l) for l in LOG.read_text().splitlines()] if LOG.exists() else []


def spent() -> int:
    return sum(r["tokens"] for r in rows())


def session(client, arm: str, seed: int) -> dict:
    tag = hashlib.md5(f"pd{arm}{seed}".encode()).hexdigest()[:6]    # pwd must not name the arm
    repo = build_pd.instance(arm, Path(f"/tmp/pr_{tag}/proofdeck"))
    preface = ""
    if arm == "specdeck_prompt":
        preface = "The suite's spec (SPEC.md, generated by specdeck) follows.\n\n" + (repo / "SPEC.md").read_text()
    m = Metered(client, preface, left=CAP - spent())
    try:
        res = agent.answer(m, MODEL, repo, [(q, t, c) for q, t, c, _ in QUESTIONS], max_calls=25)
    except SessionOver:
        res = {"answers": {}, "tool_calls": None, "commands": [], "ledger": [], "aborted": True, "seconds": None}
    res["tokens"], res["forced"] = m.tokens, m.forced
    # Harness fix 1 (every arm, from separate_doc seed 0 on): agent.py drops the whole answer
    # when its final JSON doesn't parse strictly, and keeps no copy of the text. Keep the raw
    # final text, and if agent.py found no answers, parse it again allowing control
    # characters (raw newlines) inside strings.
    raw = getattr(m, "last_text", "")
    res["raw_final"] = raw
    if not res["answers"] and raw:
        hit = re.search(r"\{.*\}", raw, re.S)
        try:
            res["answers"] = json.loads(hit.group(0), strict=False).get("answers", {}) if hit else {}
            res["lenient_parse"] = bool(res["answers"])
        except json.JSONDecodeError:
            res["lenient_parse"] = False
    graded = {q: bool(c(str(res["answers"].get(q, "")))) for q, _, c, _ in QUESTIONS}
    cmds = " ".join(res["commands"])
    read = {n: n in cmds for n in ("SPEC.md", "requirements.yaml", ".specdeck", "AGENTS.md", "REQUIREMENTS.md", "covers")}
    row = {"arm": arm, "seed": seed, "model": MODEL, "correct": sum(graded.values()), "graded": graded,
           "read": read, "turns": len(m.calls), **res}
    with LOG.open("a") as fh:
        fh.write(json.dumps(row) + "\n")
    return row


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--round", type=int, help="one session of each core arm, order rotated by round")
    ap.add_argument("--arms")
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    load_dotenv("/workspaces/python/.env")
    client = OpenAI(api_key=os.environ["OPENAI_API_KEY"])
    if args.round is not None:
        k = args.round % len(CORE)
        plan = [(a, args.round) for a in CORE[k:] + CORE[:k]]
    else:
        plan = [(a, args.seed) for a in args.arms.split(",")]
    done = {(r["arm"], r["seed"]) for r in rows()}
    print(f"spent {spent():,} of {CAP:,}", flush=True)
    for arm, seed in plan:
        if (arm, seed) in done:
            continue
        if spent() + HEADROOM > CAP:
            print(f"STOP: budget ({arm} seed{seed} not run)", flush=True)
            return 3
        r = session(client, arm, seed)
        read = ",".join(k for k, v in r["read"].items() if v) or "-"
        print(f"  {arm:16} seed{seed}  {r['correct']:>2}/10  {r['tool_calls'] or 0:>2} cmds  {r['turns']:>2} turns  "
              f"{r['tokens']:>7,} tok  forced={r['forced']}  read: {read}"
              + ("  ABORTED" if r.get("aborted") else "") + f"  | spent {spent():,}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
