"""The A/B: does an agent reason better about a suite from specdeck's spec or from the test files?

Three arms, same model (gpt-5.6-terra), same questions, same answer format:

  spec    the generated .specdeck/spec.yaml                       (what specdeck adds)
  tests   the raw test files: conftest.py + tests/test_*.py        (what the agent has today)
  both    spec + tests                                             (is the spec additive?)

Two tasks from groundtruth.py: impact ("which tests fail if this line changes like so?")
and triage ("these didn't pass; which failed on their own, which are blocked, fix what first?").
Every call is logged with its token usage; the run stops before it would pass the budget.
Resumable: finished (task, arm, batch) triples are skipped.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
from pathlib import Path

from dotenv import load_dotenv
from openai import OpenAI

from budget import Ledger, count

HERE = Path(__file__).parent
SUBJECT = os.environ.get("AB_SUBJECT", "tapedeck")
DATA = HERE / "data" / ("" if SUBJECT == "tapedeck" else SUBJECT)
REPO = Path({"tapedeck": "/workspaces/python/tapedeck", "specdeck": "/workspaces/python/specdeck"}[SUBJECT])
MODEL = os.environ.get("AB_MODEL", "gpt-5.6-terra")
# gpt-5.6-terra rejects `temperature`; gpt-4o-mini has no reasoning tokens and ignores
# reasoning_effort. Unsupported arguments are dropped on the first 400 rather than guessed at.
SLUG = MODEL.replace(".", "").replace("-", "")
ARMS = ("spec", "tests", "both", "specmap", "specrule", "testsrule", "shipped", "bound", "hub", "order", "longlast", "brief", "wiring")

SYSTEM = (f"You are a senior engineer reviewing a change to the `{REPO.name}` repository, a Python library "
          "with a pytest suite. You cannot run code and cannot see any file beyond what is shown. "
          "Reason carefully from the material given. Answer with a single JSON object and nothing else.")

# Round 3: the one fact the spec never states. Triage was 100% solvable from the DAG, and
# every arm scored what the WRONG rule scores, so the question is whether saying it is enough.
RULE = """
## How to read `depends_on`

`depends_on` is documentation order, not execution order: specdeck never reorders
tests, and the scenarios are listed in the order they run. A scenario is skipped as
*blocked* only when a prerequisite that ran **earlier** did not pass, and blocking
cascades from there. A scenario whose only failed prerequisite runs **later** is not
skipped at all — it runs normally, and can fail on its own.
"""

SPEC_INTRO = ("## The suite's specification\n\nGenerated by specdeck from the test suite. Each scenario is one "
              "test: its `logic` line is the pytest node id that runs it, its steps say what the test does "
              "and checks, `depends_on` names prerequisite scenarios (pytest skips a scenario as *blocked* "
              "when a prerequisite failed or was blocked, transitively), and the `status:` tag is from the "
              "last run.\n\n```yaml\n{spec}\n```\n")
TESTS_INTRO = "## The test files\n\n{files}\n"


def contexts() -> dict:
    spec = (REPO / ".specdeck" / "spec.yaml").read_text()
    files = [REPO / "tests" / "conftest.py", *sorted((REPO / "tests").glob("test_*.py"))]
    tests = "".join(f"### {p.relative_to(REPO)}\n\n```python\n{p.read_text()}\n```\n\n" for p in files)
    spec_block, tests_block = SPEC_INTRO.format(spec=spec), TESTS_INTRO.format(files=tests)
    v2 = (DATA / "spec_v2.yaml")
    out = {"spec": spec_block, "tests": tests_block, "both": spec_block + "\n" + tests_block}
    if v2.exists():  # round 2: the same spec plus a coverage map (see enrich.py)
        out["specmap"] = SPEC_INTRO.format(spec=v2.read_text())
    ctx = DATA / "context.md"
    if ctx.exists():  # round 4: what `specdeck context` actually emits, both fixes shipped
        out["shipped"] = ctx.read_text()
    bound = DATA / "context_bound.md"
    if bound.exists():  # round 7: the same document, now saying the coverage map is a BOUND
        out["bound"] = bound.read_text()
    hub = DATA / "context_hub.md"
    if hub.exists():  # round 8: plus hub functions collapsed to a count, not a list
        out["hub"] = hub.read_text()
    longlast = DATA / "context_long_last.md"
    if longlast.exists():  # round 10: the long notes, rule moved last — isolates the move
        out["longlast"] = longlast.read_text()
    wiring = DATA / "context_wiring.md"
    if wiring.exists():  # `--profile wiring`: the test files verbatim, no rule to dilute them
        out["wiring"] = wiring.read_text()
    brief = DATA / "context_brief.md"
    if brief.exists():  # the cheapest profile: no recorded steps, index + map + rule only
        out["brief"] = brief.read_text()
    order = DATA / "context_order.md"
    if order.exists():  # round 9: coverage notes compressed, blocking rule moved last
        out["order"] = order.read_text()
    out["specrule"] = spec_block + RULE          # round 3: spec + the blocking rule, spelled out
    out["testsrule"] = tests_block + RULE        # ...and the same sentence given to the test-file arm,
    return out                                   # so a gain can be attributed to the fact, not the format


def impact_prompt(batch: list) -> str:
    out = ["## Questions\n", "Each change below is applied ON ITS OWN to the current code and the WHOLE suite is run "
           "(with specdeck's prerequisite-skipping off, so every test runs). For each, list every test that "
           "would FAIL, as pytest node ids `tests/<file>.py::<function>`. Use an empty list if none would.\n"]
    for i, q in enumerate(batch, 1):
        out.append(f"### Q{i} — `{q['path']}` line {q['line']}\n\nContext:\n```python\n{q['snippet']}\n```\n"
                   f"Line {q['line']} changes from\n```python\n{q['original'].strip()}\n```\nto\n```python\n"
                   f"{q['mutated'].strip()}\n```\n")
    out.append('Respond exactly as: {"answers": [{"q": 1, "failing_tests": ["tests/test_x.py::test_y", ...]}, ...]}')
    return "\n".join(out)


def triage_prompt(batch: list) -> str:
    out = ["## Questions\n", "After one change, the suite was run with specdeck on. For each run below, the listed "
           "tests DID NOT PASS. Some FAILED on their own; the others were SKIPPED as blocked because a "
           "prerequisite (`depends_on`, transitively) failed or was blocked. Sort them, and name the single "
           "failing test to fix first: the one holding up the most of the others.\n"]
    for i, q in enumerate(batch, 1):
        listed = "\n".join(f"- `{n}`" for n in sorted(q["direct"] + q["blocked"]))
        out.append(f"### Run {i}\n\nDid not pass:\n{listed}\n")
    out.append('Respond exactly as: {"answers": [{"q": 1, "failed": ["tests/test_x.py::test_y", ...], '
               '"blocked": [...], "fix_first": "tests/test_x.py::test_y"}, ...]}')
    return "\n".join(out)


def batches(items: list, size: int) -> list:
    return [items[i:i + size] for i in range(0, len(items), size)]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--budget", type=int, default=500_000)
    ap.add_argument("--arms", default=",".join(ARMS))
    ap.add_argument("--tasks", default="impact,triage")
    ap.add_argument("--impact-batch", type=int, default=8)
    ap.add_argument("--triage-batch", type=int, default=5)
    ap.add_argument("--reasoning", default=None, help="reasoning_effort to send (default: the model's default)")
    ap.add_argument("--limit", type=int, default=None, help="stop after this many calls (smoke test)")
    ap.add_argument("--max-batches", type=int, default=None,
                    help="only the first N batches of each task, to replicate on a second subject cheaply")
    ap.add_argument("--dry-run", action="store_true", help="estimate tokens, call nothing")
    args = ap.parse_args()

    load_dotenv("/workspaces/python/.env")
    client = None if args.dry_run else OpenAI(api_key=os.environ["OPENAI_API_KEY"])
    name = "calls" if SUBJECT == "tapedeck" else f"calls-{SUBJECT}"
    if MODEL != "gpt-5.6-terra":
        name += f"-{SLUG}"
    ledger = Ledger(HERE / f"{name}.jsonl", args.budget)
    ctx = contexts()
    plan = []
    cap = args.max_batches
    if "impact" in args.tasks:
        for b, batch in enumerate(batches(json.loads((DATA / "impact.json").read_text()), args.impact_batch)[:cap]):
            for arm in args.arms.split(","):
                plan.append(("impact", arm, b, batch, impact_prompt(batch)))
    if "triage" in args.tasks:
        for b, batch in enumerate(batches(json.loads((DATA / "triage.json").read_text()), args.triage_batch)[:cap]):
            for arm in args.arms.split(","):
                plan.append(("triage", arm, b, batch, triage_prompt(batch)))
    # arms interleave per batch, so running out of budget leaves every arm with the same questions

    print(f"context tokens: " + ", ".join(f"{a}={count(ctx[a]):,}" for a in ARMS if a in ctx))
    print(f"{len(plan)} calls planned; spent so far {ledger.spent():,} of {args.budget:,}")
    done = ledger.done()
    made = 0
    for task, arm, b, batch, question in plan:
        if (task, arm, b) in done:
            continue
        user = ctx[arm] + "\n" + question
        est = count(SYSTEM) + count(user) + 4_000  # room for the answer and any reasoning
        if not ledger.can_afford(est):
            print(f"STOP: {task}/{arm}/{b} would need ~{est:,} tokens; spent {ledger.spent():,} of {args.budget:,}")
            return 3
        if args.dry_run:
            print(f"  would call {task}/{arm}/{b}: ~{est:,} tokens")
            continue
        t0 = time.time()
        kw = {"reasoning_effort": args.reasoning} if args.reasoning else {}
        msgs = [{"role": "system", "content": SYSTEM}, {"role": "user", "content": user}]
        while True:
            try:
                r = client.chat.completions.create(model=MODEL, response_format={"type": "json_object"},
                                                   messages=msgs, **kw)
                break
            except Exception as exc:
                bad = next((k for k in list(kw) if k in str(exc)), None)
                if bad is None:
                    raise
                print(f"  (this model rejects {bad}; dropping it)", flush=True)
                kw.pop(bad)
        u = r.usage
        usage = {"prompt_tokens": u.prompt_tokens, "completion_tokens": u.completion_tokens, "total_tokens": u.total_tokens,
                 "cached_tokens": getattr(u.prompt_tokens_details, "cached_tokens", 0) or 0,
                 "reasoning_tokens": getattr(u.completion_tokens_details, "reasoning_tokens", 0) or 0}
        text = r.choices[0].message.content or ""
        try:
            answer = json.loads(text)
        except json.JSONDecodeError:
            answer = {"_unparsed": text}
        ledger.log(task=task, arm=arm, batch=b, model=MODEL, reasoning=args.reasoning, usage=usage,
                   seconds=round(time.time() - t0, 1), question_ids=[q["id"] for q in batch], answer=answer)
        made += 1
        print(f"  {task}/{arm}/{b}: {usage['prompt_tokens']:,} in ({usage['cached_tokens']:,} cached) + "
              f"{usage['completion_tokens']:,} out ({usage['reasoning_tokens']:,} reasoning) in {time.time() - t0:.0f}s"
              f" — spent {ledger.spent():,}", flush=True)
        if args.limit and made >= args.limit:
            print("limit reached")
            break
    t = ledger.totals().get("all", {})
    print(f"done: {t.get('calls', 0)} calls, {t.get('total', 0):,} tokens of {args.budget:,}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
