"""`specdeck srs` — the software requirements specification, generated, in ISO/IEC/IEEE 29148:2018 form.

The content follows §9.6 (SRS content; example outline in §8.5.2), in the standard's order:
identification (§9.2.1), the introduction (§9.6.2–9.6.9), the specified requirements grouped by
type (§9.6.11–9.6.18), verification (§9.6.19) and supporting information (§9.6.20).

What a test run knows is filled in from the run: every requirement with its attributes (§5.2.8),
its verification status and the tests that verify it, and a traceability matrix. What only people
know — purpose, scope, users, limitations — comes from an optional `srs:` block in
requirements.yaml. A section with nothing to say is marked *to be supplied (TBS)* rather than left
out, because §5.2.6 counts a set with open TBx items as incomplete and the reader should see it.

The document declares its tailoring (§4.5.2): it is generated for tailored conformance to the
content of §9.6, and lists what it does not cover.
"""
from __future__ import annotations

import subprocess
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

from .requirements import STANDARD, TYPES, Requirements

# §9.6.2–9.6.9 and §9.6.20: written by people, in the `srs:` block of requirements.yaml.
INTRO = [
    ("purpose", "§9.6.2", "Purpose"),
    ("scope", "§9.6.3", "Scope"),
    ("product_perspective", "§9.6.4", "Product perspective"),
    ("product_functions", "§9.6.5", "Product functions"),
    ("user_characteristics", "§9.6.6", "User characteristics"),
    ("limitations", "§9.6.7", "Limitations"),
    ("assumptions", "§9.6.8", "Assumptions and dependencies"),
    ("apportioning", "§9.6.9", "Apportioning of requirements"),
]
# §9.6.11–9.6.18, in the standard's order, then the two further types of §5.2.8.3.
SECTIONS = ["interface", "functional", "usability", "performance", "logical-database", "design-constraint",
            "standards-compliance", "software-attribute", "process", "human-factors"]
TBS = "_To be supplied (TBS)._"
REVIEW = [("Appropriate", "the detail fits the level of the thing it describes, without needless design constraints"),
          ("Feasible", "it can be realised within cost, schedule and technical limits, at acceptable risk"),
          ("Correct", "it accurately represents the need it came from")]


def _revision(root: Path) -> str:
    try:
        sha = subprocess.run(["git", "-C", str(root), "rev-parse", "--short", "HEAD"], capture_output=True,
                             text=True, timeout=10).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        sha = ""
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    return f"generated {stamp}" + (f" from commit {sha}" if sha else "")


def _attrs(r: dict) -> str:
    pairs = [("Rationale", r.get("rationale") or r.get("why")), ("Type", r.get("type")),
             ("Priority", r.get("priority")), ("Owner", r.get("owner")), ("Risk", r.get("risk")),
             ("Difficulty", r.get("difficulty")),
             ("Verification method", ", ".join(r.get("verification") or ["test"])),
             ("Implements", r.get("standard"))]
    return "\n".join(f"- **{k}:** {' '.join(str(v).split())}" for k, v in pairs if v)


def _status(r: dict) -> str:
    return r.get("status") or "not run"


def build(reqs: Requirements, report: Optional[dict], scenarios: Optional[list], srs: dict, root: Path) -> str:
    """The SRS as Markdown. ``report``: the requirements report of the last run (statuses and the
    scenarios that verify each requirement), or None before any run. ``scenarios``: the generated
    spec's scenarios, for the untraced-test list. ``srs``: the `srs:` block of requirements.yaml."""
    from .quality import check_set

    by_id = {r["id"]: r for r in (report or {}).get("requirements", [])}
    rows = [dict(r.to_dict(), **{k: by_id.get(r.id, {}).get(k) for k in ("status", "scenarios")})
            for r in reqs.items.values()]
    title = srs.get("title") or "Software requirements specification"
    out = [f"# {title}", "",
           f"**Revision:** {_revision(root)} · **Prepared to:** {STANDARD}, content of §9.6 (identification "
           f"§9.2.1)", "",
           "## Tailoring", "",
           f"This document is generated by specdeck for tailored conformance (§4.5.2) to the information-item "
           f"content of {STANDARD} §9.6. The requirements, their attributes (§5.2.8), their verification "
           f"status and their traceability to tests come from the project's requirements file and its last test "
           f"run. Sections the project has not written are marked *to be supplied*. Verification by test is "
           f"automated; inspection, analysis/simulation and demonstration (§6.5.2) are recorded as declared on "
           f"each requirement. Life-cycle processes (Clause 6) are outside this document.", ""]

    out += ["## 1 Introduction", "", "### 1.1 Overview (§9.6.1)", "",
            srs.get("overview") or f"{len(rows)} requirements, verified against the test suite of this project.", ""]
    for n, (key, clause, name) in enumerate(INTRO, start=2):
        body = srs.get(key)
        if key == "product_functions" and not body:
            functions = [r for r in rows if r.get("type") == "functional"]
            body = "\n".join(f"- {r['statement']} (`{r['id']}`)" for r in functions) or None
        out += [f"### 1.{n} {name} ({clause})", "", str(body).strip() if body else TBS, ""]

    out += ["## 2 Specified requirements (§9.6.10)", ""]
    groups = {t: [r for r in rows if r.get("type") == t] for t in SECTIONS}
    untyped = [r for r in rows if not r.get("type")]
    n = 0
    for t in SECTIONS:
        if not groups[t] and t in ("process", "human-factors"):
            continue                                       # §5.2.8.3 extras: only when used
        n += 1
        clause, name = TYPES[t].split(" ", 1)
        out += [f"### 2.{n} {name} ({clause})", ""]
        if not groups[t]:
            out += ["_None specified._", ""]
        for r in groups[t]:
            out += _requirement(r)
    if untyped:
        n += 1
        out += [f"### 2.{n} Requirements without a type", "",
                "These have no `type` attribute (§5.2.8.3), so they cannot be placed in a section above.", ""]
        for r in untyped:
            out += _requirement(r)

    out += ["## 3 Verification (§9.6.19)", "",
            "Each requirement, the method that verifies it (§6.5.2), the tests that do, and the result of the last "
            "run.", "",
            "| Requirement | Method | Verified by | Status |", "|---|---|---|---|"]
    for r in rows:
        tests = ", ".join(f"`{s.get('nodeid') or s['id']}`" for s in r.get("scenarios") or []) or "—"
        out.append(f"| `{r['id']}` | {', '.join(r.get('verification') or ['test'])} | {tests} | {_status(r)} |")
    counts = {}
    for r in rows:
        counts[_status(r)] = counts.get(_status(r), 0) + 1
    out += ["", "**Summary:** " + ", ".join(f"{v} {k}" for k, v in sorted(counts.items())), ""]

    findings = check_set(reqs, scenarios)
    out += ["### 3.1 Requirement quality (§5.2.4–5.2.7)", ""]
    if findings:
        out += ["Findings of `specdeck validate` against the criteria a tool can check:", ""]
        out += [f"- `{d.scenario}` {d.message}" for d in findings]
    else:
        out.append("No findings: every requirement meets the criteria a tool can check.")
    out += ["", "### 3.2 For review (§5.2.5)", "",
            "These characteristics need judgement and are not checked by the tool. Confirm each requirement is:", ""]
    out += [f"- **{k}:** {v}" for k, v in REVIEW]

    out += ["", "## 4 Supporting information (§9.6.20)", "",
            str(srs.get("supporting_information")).strip() if srs.get("supporting_information") else
            f"The full test scenarios are in the generated spec (`.specdeck/spec.yaml`, readable as SPEC.md via "
            f"`specdeck context`). {len(scenarios or [])} scenarios in the last run.", ""]
    return "\n".join(out).rstrip() + "\n"


def _requirement(r: dict) -> list:
    tests = ", ".join(f"`{s.get('nodeid') or s['id']}`" for s in r.get("scenarios") or [])
    return [f"#### `{r['id']}`", "", f"{' '.join(r['statement'].split())}", "", _attrs(r),
            f"- **Verification status:** {_status(r)}" + (f" — verified by {tests}" if tests else ""), ""]
