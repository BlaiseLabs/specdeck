"""`specdeck agents` — the project's rules, written into the agent instructions file (AGENTS.md).

An instructions file for coding agents is mostly rules: decisions the code must keep to, the
standards it follows, and what has to be true before a change is done. Written by hand, such a
file goes stale and nothing tells an agent which rules still hold. Here the rules are
requirements in requirements.yaml, under the types of ISO/IEC/IEEE 29148:2018:

- ``design-constraint`` (§9.6.16): decisions that limit how the software may be built. The
  rationale is the decision record; the tests that verify it fail when it is broken.
- ``standards-compliance`` (§9.6.17): requirements that come from a standard or regulation.
- ``process`` (§5.2.8.3): requirements on how the work is done, which is what a team calls its
  Definition of Done.

Each rule is written with its rationale, the tests that verify it and its verification status
from the last run, so the file says which rules hold now and which are broken. A rule that no
test verifies is listed with its declared method (§6.5.2) for the agent to check by hand.

Above the rules goes the adherence policy (``adherence.py``): what keeping a rule means, from
specdeck's default clauses as changed by the project's `adherence:` block.

Only the block between the markers is written. The rest of an existing file is left as it is,
so hand-written instructions and the generated rules share one file.
"""
from __future__ import annotations

from pathlib import Path
from typing import Optional

from .requirements import STANDARD, TYPES, Requirements

BEGIN = "<!-- specdeck:rules — generated by `specdeck agents` from requirements.yaml; edit that file, not this block -->"
END = "<!-- specdeck:end -->"
RULES = [("design-constraint", "Design constraints"),
         ("standards-compliance", "Standards compliance"),
         ("process", "Definition of Done")]
STATUS = {"met": "holds in the last run", "failing": "**broken in the last run**",
          "blocked": "blocked in the last run", "not run": "not run in the last run",
          "untested": "no test verifies it"}


def _rule(r: dict) -> list:
    out = [f"- **{' '.join(r['statement'].split())}** (`{r['id']}`)"]
    if r.get("rationale"):
        out.append(f"  Why: {' '.join(str(r['rationale']).split())}")
    if r.get("standard"):
        out.append(f"  Implements: {r['standard']}")
    tests = [s.get("nodeid") or s["id"] for s in r.get("scenarios") or []]
    other = [m for m in r.get("verification") or ["test"] if m != "test"]
    if tests:
        out.append(f"  Verified by: {', '.join(f'`{t}`' for t in tests)} — {STATUS.get(r.get('status'), r.get('status') or 'not run yet')}")
    elif other:
        out.append(f"  Verified by {' and '.join(other)}, not by a test: check it yourself before finishing.")
    else:
        out.append("  No test verifies it yet: check it yourself before finishing.")
    return out


def block(reqs: Requirements, report: Optional[dict]) -> str:
    """The generated block, markers included."""
    by_id = {r["id"]: r for r in (report or {}).get("requirements", [])}
    rows = [dict(r.to_dict(), **{k: by_id.get(r.id, {}).get(k) for k in ("status", "scenarios")})
            for r in reqs.items.values()]
    out = [BEGIN, "", "## Project rules", "",
           f"The rules below are requirements in `requirements.yaml`, typed as in {STANDARD}. Each is "
           "checked by the tests named under it; the status is from the last test run. Keep to every rule "
           "that holds. A broken rule is the first thing to fix, or to raise with a person if the rule "
           "itself looks wrong. Change a rule by editing `requirements.yaml`, never this block.", ""]
    if reqs.adherence.clauses:   # the adherence policy (adherence.py): what keeping a rule means
        out += [reqs.adherence.text(), ""]
    broken = [r for r in rows if r.get("type") in dict(RULES) and r.get("status") == "failing"]
    names = ", ".join(f"`{r['id']}`" for r in broken)
    if broken:   # first, where an agent reading from the top meets it before anything else
        out += [f"**Broken in the last run:** {names} — fix {'this' if len(broken) == 1 else 'these'} "
                "before anything else.", ""]
    any_rule = False
    for t, name in RULES:
        mine = [r for r in rows if r.get("type") == t]
        if not mine:
            continue
        any_rule = True
        clause = TYPES[t].split(" ", 1)[0]
        out += [f"### {name} ({clause})", ""]
        for r in mine:
            out += _rule(r)
        out.append("")
    if not any_rule:
        out += ["No rules yet. Add requirements with `type: design-constraint`, `standards-compliance` or "
                "`process` to `requirements.yaml`, then run `specdeck agents` again.", ""]
    out += ["### Before you finish", "",
            "Run `pytest`, then `specdeck validate`, then `specdeck agents` to refresh this block."]
    if broken:
        out += ["", f"Still broken from the last run: {names}."]
    out += ["", END]
    return "\n".join(out)


# The instruction files coding agents read on their own. Claude Code reads CLAUDE.md, and AGENTS.md only
# when there is no CLAUDE.md (v2.1.277, 2026-09-18); Codex, Cursor, Copilot and others read AGENTS.md.
# So the block goes into whichever exist, both when both do, and AGENTS.md when neither does.
INSTRUCTION_FILES = ("CLAUDE.md", "AGENTS.md")


def targets(root: Path) -> list:
    """The instruction files to write the block into, in ``root``."""
    found = [root / name for name in INSTRUCTION_FILES if (root / name).exists()]
    return found or [root / "AGENTS.md"]


def update(text: Optional[str], new_block: str) -> str:
    """``text`` with the generated block replaced, or appended when it has none."""
    if not text:
        return new_block + "\n"
    start, end = text.find(BEGIN), text.find(END)
    if start != -1 and end > start:
        return text[:start] + new_block + text[end + len(END):]
    return text.rstrip("\n") + "\n\n" + new_block + "\n"


def write(path: Path, reqs: Requirements, report: Optional[dict]) -> str:
    """Write the block into ``path`` and return what the file now holds."""
    old = path.read_text(encoding="utf-8") if path.exists() else None
    text = update(old, block(reqs, report))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return text
